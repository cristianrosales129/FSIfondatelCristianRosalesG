    private void BAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BAceptarActionPerformed
        // TODO add your handling code here:
       

    
    String usr = TUsuario.getText().trim();
    String nip = new String(TPassword.getPassword());

    if (usr.isEmpty() || nip.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Escribe tu usuario y tu NIP");
        return;
    }

    String sql = String.format(rol, usr, nip);
    String tipo = cnx.obtenerDato(sql);

    if (tipo == null) {
        tipo = "";
    }

    switch (tipo.toLowerCase()) {
        case "gerente":
        case "administrador":
            FAdministrador fa = new FAdministrador(usr);
            cnx.desconectar();
            this.dispose();
            fa.setVisible(true);
            break;

        case "mesero":
            FMesero fm = new FMesero(usr);
            cnx.desconectar();
            this.dispose();
            fm.setVisible(true);
            break;

        case "cocinero":
            FCocinero fc = new FCocinero(usr);
            cnx.desconectar();
            this.dispose();
            fc.setVisible(true);
            break;

        case "cajero":
            FCajero fj = new FCajero(usr);
            cnx.desconectar();
            this.dispose();
            fj.setVisible(true);
            break;

        case "":
            intentos++;
            JOptionPane.showMessageDialog(this, "Credenciales incorrectas");
            TPassword.setText("");
            if (intentos >= 3) {
                JOptionPane.showMessageDialog(this, "Intentos agotados");
                cnx.desconectar();
                System.exit(0);
            }
            break;

        default: // puestos sin ventana asignada
            JOptionPane.showMessageDialog(this, "Tu puesto no tiene acceso al sistema");
            break;
    }

    }//GEN-LAST:event_BAceptarActionPerformed

