    private void BtnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnRegistrarActionPerformed
                                          
    String cla = TClave.getText().trim();
    String nombre = TTitulo.getText().trim();

    if (cla.isEmpty() || nombre.isEmpty() || cartel == null) {
        JOptionPane.showMessageDialog(this, "Completa la clave, el nombre y selecciona una fotografía");
        return;
    }

    try {
        int id = Integer.parseInt(cla);
        
        // Creamos el objeto Alimento igual que Peliculas
        Alimento alimento = new Alimento(id, nombre, "Sin descripción", 0.0f, cartel, "General", "disponible");

        if (alimento.insertar(cnx) == 1) {
        cargarAlimentos();
            JOptionPane.showMessageDialog(this, "¡Alimento registrado correctamente!");
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar el alimento");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "La clave debe ser un número entero");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al registrar: " + e.getMessage());
    }

  
    }//GEN-LAST:event_BtnRegistrarActionPerformed

    private void TConsultasMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TConsultasMousePressed
                                  
    int ren = TConsultas.getSelectedRow();
    DefaultTableModel modelo = (DefaultTableModel) TConsultas.getModel();
    
    if (ren >= 0) {
        // Validamos que los valores no sean nulos para evitar el NullPointerException
        Object valClave = modelo.getValueAt(ren, 0);
        Object valTitulo = modelo.getValueAt(ren, 1);
        
        if (valClave != null) {
            TClave.setText(valClave.toString());
        } else {
            TClave.setText("");
        }
        
        if (valTitulo != null) {
            TTitulo.setText(valTitulo.toString());
        } else {
            TTitulo.setText("");
        }
        
        // Manejo seguro de la imagen en la columna 4
        Object objFoto = modelo.getValueAt(ren, 4);
        
        if (objFoto instanceof ImageIcon) {
            cartel = new ImageIcon(cnx.escalarImagen(((ImageIcon) objFoto).getImage(), 194, 235));
            JTCartel.setIcon(cartel);
        } else {
            cartel = null;
            JTCartel.setIcon(null);
        }
    }


        
    }//GEN-LAST:event_TConsultasMousePressed

    private void BtnAbrirCartelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnAbrirCartelActionPerformed
        // TODO add your handling code here:
        JFileChooser fc = new JFileChooser(System.getProperty("user.dir"));
        if (fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            File archivo = fc.getSelectedFile();
            cartel = new ImageIcon(archivo.getAbsolutePath());
            JTCartel.setIcon(new ImageIcon(
                cnx.escalarImagen(cartel.getImage(), 194, 235)
            ));
        }
    }//GEN-LAST:event_BtnAbrirCartelActionPerformed

